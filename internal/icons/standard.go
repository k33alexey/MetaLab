package icons

import "slices"

// The library of standard pictures: every value of БиблиотекаКартинок as the
// syntax assistant of 8.3.27 lists it, each under the names the
// configurations write - StdPicture.<Name> in the files of forms and
// commands, БиблиотекаКартинок.<Russian> in code - so that a configuration
// moved from the prototype draws the pictures it names without mapping them
// (docs/requirements/ICONS.md, «Стандартные картинки»; the window that offers
// them is docs/block-00/standartnye-kartinki.md).
//
// A picture is drawn once. Where the prototype's library shows the same
// picture as a command of the configurator - print, find, the floppy of
// write - the picture is that command's icon; where the two differ - the
// configurator deletes with a red cross, the library with a red disc - each
// keeps its own, as the prototype draws them. A common action of Studio that
// has no text takes its picture from here (the owner's decision of
// 16.10.2026).

// StandardPicture is one picture of the library: the name the files write,
// its Russian name, a second Russian spelling where the help gives one (two
// pictures are also written with a Latin «c» in «Восклицательный», and
// configurations use that spelling), whether the window hides it, and the
// icon that draws it - none while it is not drawn yet.
//
// A hidden picture the configurator keeps and the platform draws, but the
// window «Выбор картинки» has no row for it, so Studio does not offer it
// either and shows it only where it is already set: ten pictures of objects
// the help keeps for the compatibility mode of 8.1, four it no longer
// recommends since 8.3.17 (the pictures of an input field came in their
// place) and twenty-five it hides with no reason given - by their meaning
// the commands of lists and forms of the ordinary application
// (docs/block-00/standartnye-kartinki.md).
type StandardPicture struct {
	Name     string
	Russian  string
	Spelling string
	Hidden   bool
	Icon     string
}

// StandardPictures is the library in the order of the help.
func StandardPictures() []StandardPicture {
	return slices.Clone(standardPictures)
}

// LookupStandard finds a picture of the library by any of its names.
func LookupStandard(name string) (StandardPicture, bool) {
	index := slices.IndexFunc(standardPictures, func(picture StandardPicture) bool {
		return picture.Name == name || picture.Russian == name || picture.Spelling == name
	})
	if index < 0 {
		return StandardPicture{}, false
	}
	return standardPictures[index], true
}

