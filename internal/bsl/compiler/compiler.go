func expressionPath(expression syntax.Expression) ([]string, bool) {
	switch node := expression.(type) {
	case *syntax.IdentifierExpression:
		if node.Qualifier != "" {
			return []string{node.Qualifier, node.Name}, true
		}
		return []string{node.Name}, true
	case *syntax.MemberExpression:
		parts, ok := expressionPath(node.Receiver)
		if !ok {
			return nil, false
		}
		return append(parts, node.Name), true
	default:
		return nil, false
	}
}

func (c *functionCompiler) addObjectOperation(name string, arity int, dynamic bool, references []bytecode.VariableReference, span syntax.Span) uint16 {
	if arity > math.MaxUint16 || len(c.function.Objects) > math.MaxUint16 {
		c.owner.report(c.filename, span, "BSL3041", "too many object operations or arguments")
		return 0
	}
	operation := bytecode.ObjectOperation{Name: name, Arity: uint16(arity), Dynamic: dynamic, References: references}
	index := uint16(len(c.function.Objects))
	c.function.Objects = append(c.function.Objects, operation)
	return index
}

func (c *functionCompiler) hasModule(name string) bool {
	_, ok := c.owner.moduleByName[strings.ToLower(name)]
	return ok
}

func (c *functionCompiler) isModuleQualifier(name string) bool {
	folded := strings.ToLower(name)
	if _, local := c.locals[folded]; local {
		return false
	}
	for _, variable := range c.owner.program.Modules[c.module].Variables {
		if strings.EqualFold(variable.Name, name) {
			return false
		}
	}
	return c.hasModule(name)
}

func (c *functionCompiler) hasUnqualifiedVariable(name string) bool {
	if _, ok := c.locals[strings.ToLower(name)]; ok {
		return true
	}
	for _, variable := range c.owner.program.Modules[c.module].Variables {
		if strings.EqualFold(variable.Name, name) {
			return true
		}
	}
	return false
}

func (c *functionCompiler) compileErrorDescription(call *syntax.CallExpression) {
	if len(call.Arguments) != 0 {
		c.owner.report(c.filename, call.SourceSpan, "BSL3037", "ErrorDescription expects no arguments")
	}
	if len(c.exceptions) == 0 {
		c.owner.report(c.filename, call.SourceSpan, "BSL3038", "ErrorDescription is only allowed inside an Except block")
		c.emitConstant(bytecode.String(""), call.SourceSpan)
		return
	}
	c.emit(bytecode.OpErrorDescription, c.exceptions[len(c.exceptions)-1], call.SourceSpan)
}

func (c *functionCompiler) resolveRoutine(qualifier, name string, span syntax.Span) (routineEntry, bool) {
	module := c.module
	if qualifier != "" {
		resolved, ok := c.owner.moduleByName[strings.ToLower(qualifier)]
		if !ok {
			c.owner.report(c.filename, span, "BSL3026", "unknown module "+qualifier)
			return routineEntry{}, false
		}
		module = resolved
	}
	entry, ok := c.owner.routineByName[c.owner.routineKey(module, name)]
	if !ok {
		c.owner.report(c.filename, span, "BSL3033", "unknown routine "+name)
		return routineEntry{}, false
	}
	if module != c.module && !entry.routine.Export {
		c.owner.report(c.filename, span, "BSL3034", "routine is not exported: "+qualifier+"."+name)
		return routineEntry{}, false
	}
	return entry, true
}

func (c *functionCompiler) referenceForExpression(expression syntax.Expression) (bytecode.VariableReference, bool) {
	switch node := expression.(type) {
	case *syntax.IdentifierExpression:
		return c.resolveVariable(node.Qualifier, node.Name, false, node.SourceSpan)
	case *syntax.MemberExpression:
		if identifier, ok := node.Receiver.(*syntax.IdentifierExpression); ok && c.isModuleQualifier(identifier.Name) {
			return c.resolveVariable(identifier.Name, node.Name, false, node.SourceSpan)
		}
	}
	return bytecode.VariableReference{}, false
}

func (c *functionCompiler) compileLogical(expression *syntax.BinaryExpression) {
	c.compileExpression(expression.Left)
	opcode := bytecode.OpJumpIfFalseKeep
	if expression.Operator == syntax.Or {
		opcode = bytecode.OpJumpIfTrueKeep
	}
	endJump := c.emitJump(opcode, expression.SourceSpan)
	c.emit(bytecode.OpPop, 0, expression.SourceSpan)
	c.compileExpression(expression.Right)
	c.emit(bytecode.OpBoolean, 0, expression.Right.NodeSpan())
	c.patchJump(endJump, len(c.function.Code), expression.SourceSpan)
}

func (c *functionCompiler) compileIf(statement *syntax.IfStatement) {
	endJumps := make([]int, 0, len(statement.Branches))
	for _, branch := range statement.Branches {
		c.compileExpression(branch.Condition)
		falseJump := c.emitJump(bytecode.OpJumpIfFalse, branch.SourceSpan)
		for _, child := range branch.Body {
			c.compileStatement(child)
		}
		endJumps = append(endJumps, c.emitJump(bytecode.OpJump, branch.SourceSpan))
		c.patchJump(falseJump, len(c.function.Code), branch.SourceSpan)
	}
	for _, child := range statement.ElseBody {
		c.compileStatement(child)
	}
	end := len(c.function.Code)
	for _, jump := range endJumps {
		c.patchJump(jump, end, statement.SourceSpan)
	}
}

func (c *functionCompiler) compileWhile(statement *syntax.WhileStatement) {
	start := len(c.function.Code)
	c.compileExpression(statement.Condition)
	exitJump := c.emitJump(bytecode.OpJumpIfFalse, statement.SourceSpan)
	c.loops = append(c.loops, loopContext{continueTarget: start})
	for _, child := range statement.Body {
		c.compileStatement(child)
	}
	loop := c.loops[len(c.loops)-1]
	c.loops = c.loops[:len(c.loops)-1]
	c.emitTargetJump(bytecode.OpJump, start, statement.SourceSpan)
	exit := len(c.function.Code)
	c.patchJump(exitJump, exit, statement.SourceSpan)
	for _, jump := range loop.breakJumps {
		c.patchJump(jump, exit, statement.SourceSpan)
	}
}

func (c *functionCompiler) compileFor(statement *syntax.ForStatement) {
	counter := c.ensureLocal(statement.Variable, statement.SourceSpan)
	limit := c.allocateLocal(statement.SourceSpan)
	c.compileExpression(statement.Initial)
	c.emit(bytecode.OpStoreLocal, counter, statement.SourceSpan)
	c.compileExpression(statement.Limit)
	c.emit(bytecode.OpStoreLocal, limit, statement.SourceSpan)

	start := len(c.function.Code)
	c.emit(bytecode.OpLoadLocal, counter, statement.SourceSpan)
	c.emit(bytecode.OpLoadLocal, limit, statement.SourceSpan)
	c.emit(bytecode.OpLessEqual, 0, statement.SourceSpan)
	exitJump := c.emitJump(bytecode.OpJumpIfFalse, statement.SourceSpan)
	c.loops = append(c.loops, loopContext{continueTarget: -1})
	for _, child := range statement.Body {
		c.compileStatement(child)
	}
	loopIndex := len(c.loops) - 1
	increment := len(c.function.Code)
	c.loops[loopIndex].continueTarget = increment
	for _, jump := range c.loops[loopIndex].continueJumps {
		c.patchJump(jump, increment, statement.SourceSpan)
	}
	loop := c.loops[loopIndex]
	c.loops = c.loops[:loopIndex]

	c.emit(bytecode.OpLoadLocal, counter, statement.SourceSpan)
	c.emitConstant(bytecode.Number(1), statement.SourceSpan)
	c.emit(bytecode.OpAdd, 0, statement.SourceSpan)
	c.emit(bytecode.OpStoreLocal, counter, statement.SourceSpan)
	c.emitTargetJump(bytecode.OpJump, start, statement.SourceSpan)
	exit := len(c.function.Code)
	c.patchJump(exitJump, exit, statement.SourceSpan)
	for _, jump := range loop.breakJumps {
		c.patchJump(jump, exit, statement.SourceSpan)
	}
}

func (c *functionCompiler) compileForEach(statement *syntax.ForEachStatement) {
	iterator := c.ensureLocal(statement.Variable, statement.SourceSpan)
	collection := c.allocateLocal(statement.SourceSpan)
	index := c.allocateLocal(statement.SourceSpan)
	c.compileExpression(statement.Collection)
	c.emit(bytecode.OpStoreLocal, collection, statement.SourceSpan)
	c.emitConstant(bytecode.Number(0), statement.SourceSpan)
	c.emit(bytecode.OpStoreLocal, index, statement.SourceSpan)

	start := len(c.function.Code)
	c.emit(bytecode.OpLoadLocal, index, statement.SourceSpan)
	c.emit(bytecode.OpLoadLocal, collection, statement.SourceSpan)
	c.emit(bytecode.OpArrayLength, 0, statement.SourceSpan)
	c.emit(bytecode.OpLess, 0, statement.SourceSpan)
	exitJump := c.emitJump(bytecode.OpJumpIfFalse, statement.SourceSpan)
	c.emit(bytecode.OpLoadLocal, collection, statement.SourceSpan)
	c.emit(bytecode.OpLoadLocal, index, statement.SourceSpan)
	c.emit(bytecode.OpArrayElement, 0, statement.SourceSpan)
	c.emit(bytecode.OpStoreLocal, iterator, statement.SourceSpan)

	c.loops = append(c.loops, loopContext{continueTarget: -1})
	for _, child := range statement.Body {
		c.compileStatement(child)
	}
	loopIndex := len(c.loops) - 1
	increment := len(c.function.Code)
	c.loops[loopIndex].continueTarget = increment
	for _, jump := range c.loops[loopIndex].continueJumps {
		c.patchJump(jump, increment, statement.SourceSpan)
	}
	loop := c.loops[loopIndex]
	c.loops = c.loops[:loopIndex]

	c.emit(bytecode.OpLoadLocal, index, statement.SourceSpan)
	c.emitConstant(bytecode.Number(1), statement.SourceSpan)
	c.emit(bytecode.OpAdd, 0, statement.SourceSpan)
	c.emit(bytecode.OpStoreLocal, index, statement.SourceSpan)
	c.emitTargetJump(bytecode.OpJump, start, statement.SourceSpan)
	exit := len(c.function.Code)
	c.patchJump(exitJump, exit, statement.SourceSpan)
	for _, jump := range loop.breakJumps {
		c.patchJump(jump, exit, statement.SourceSpan)
	}
}

func (c *functionCompiler) compileLoopControl(span syntax.Span, breaking bool) {
	if len(c.loops) == 0 {
		name := "Continue"
		if breaking {
			name = "Break"
		}
		c.owner.report(c.filename, span, "BSL3012", name+" is only allowed inside a loop")
		return
	}
	loop := &c.loops[len(c.loops)-1]
	if breaking {
		loop.breakJumps = append(loop.breakJumps, c.emitJump(bytecode.OpJump, span))
		return
	}
	if loop.continueTarget >= 0 {
		c.emitTargetJump(bytecode.OpJump, loop.continueTarget, span)
	} else {
		loop.continueJumps = append(loop.continueJumps, c.emitJump(bytecode.OpJump, span))
	}
}

func (c *functionCompiler) ensureLocal(name string, span syntax.Span) uint16 {
	folded := strings.ToLower(name)
	if index, ok := c.locals[folded]; ok {
		return index
	}
	index := c.allocateLocal(span)
	c.locals[folded] = index
	c.setLocalName(index, name)
	return index
}

func (c *functionCompiler) allocateLocal(span syntax.Span) uint16 {
	if c.nextLocal >= math.MaxUint16 {
		c.owner.report(c.filename, span, "BSL3011", "too many local variables in routine")
		return 0
	}
	index := uint16(c.nextLocal)
	c.nextLocal++
	c.localNames = append(c.localNames, "")
	return index
}

func (c *functionCompiler) setLocalName(index uint16, name string) {
	if int(index) < len(c.localNames) {
		c.localNames[index] = name
	}
}

func (c *functionCompiler) emitJump(opcode bytecode.Opcode, span syntax.Span) int {
	index := len(c.function.Code)
	c.emit(opcode, 0, span)
	return index
}

func (c *functionCompiler) emitTargetJump(opcode bytecode.Opcode, target int, span syntax.Span) {
	index := c.emitJump(opcode, span)
	c.patchJump(index, target, span)
}

func (c *functionCompiler) patchJump(index, target int, span syntax.Span) {
	if index < 0 || index >= len(c.function.Code) || target < 0 || target > math.MaxUint16 {
		c.owner.report(c.filename, span, "BSL3013", "routine is too large for a control-flow jump")
		return
	}
	c.function.Code[index].Operand = uint16(target)
}

func (c *functionCompiler) hasJumpTarget(target int) bool {
	for _, instruction := range c.function.Code {
		if (instruction.Opcode == bytecode.OpJump || instruction.Opcode == bytecode.OpJumpIfFalse ||
			instruction.Opcode == bytecode.OpJumpIfTrueKeep || instruction.Opcode == bytecode.OpJumpIfFalseKeep) && int(instruction.Operand) == target {
			return true
		}
	}
	return false
}

func (c *functionCompiler) emitConstant(value bytecode.Value, span syntax.Span) {
	if len(c.function.Constants) > math.MaxUint16 {
		c.owner.report(c.filename, span, "BSL3010", "too many constants in routine")
		return
	}
	index := uint16(len(c.function.Constants))
	c.function.Constants = append(c.function.Constants, value)
	c.emit(bytecode.OpConstant, index, span)
}

func (c *functionCompiler) emitCall(callSite uint16, arity int, span syntax.Span) {
	c.function.Code = append(c.function.Code, bytecode.Instruction{Opcode: bytecode.OpCall, Operand: callSite, Span: span})
	c.depth += 1 - arity
	if c.depth > c.maximum {
		c.maximum = c.depth
	}
}

func (c *functionCompiler) emit(opcode bytecode.Opcode, operand uint16, span syntax.Span) {
	c.function.Code = append(c.function.Code, bytecode.Instruction{Opcode: opcode, Operand: operand, Span: span})
	switch opcode {
	case bytecode.OpConstant, bytecode.OpLoadLocal, bytecode.OpLoadModule, bytecode.OpErrorDescription:
		c.depth++
	case bytecode.OpStoreLocal, bytecode.OpStoreModule, bytecode.OpJumpIfFalse, bytecode.OpPop, bytecode.OpRaise:
		c.depth--
	case bytecode.OpSetProperty:
		c.depth -= 2
	case bytecode.OpSetIndex:
		c.depth -= 3
	case bytecode.OpConstruct:
		operation := c.function.Objects[operand]
		c.depth += 1 - int(operation.Arity)
		if operation.Dynamic {
			c.depth--
		}
	case bytecode.OpCallMethod:
		c.depth -= int(c.function.Objects[operand].Arity)
	case bytecode.OpMetadataGet:
		c.depth++
	case bytecode.OpMetadataCall:
		c.depth += 1 - int(c.function.Objects[operand].Arity)
	case bytecode.OpAdd, bytecode.OpSubtract, bytecode.OpMultiply, bytecode.OpDivide,
		bytecode.OpModulo, bytecode.OpEqual, bytecode.OpNotEqual, bytecode.OpLess,
		bytecode.OpLessEqual, bytecode.OpGreater, bytecode.OpGreaterEqual,
		bytecode.OpAnd, bytecode.OpOr, bytecode.OpArrayElement, bytecode.OpGetIndex:
		c.depth--
	case bytecode.OpReturn:
		c.depth--
	}
	if c.depth > c.maximum {
		c.maximum = c.depth
	}
}

func (c *compiler) report(filename string, span syntax.Span, code, message string) {
	if span.Start.Line == 0 {
		span.Start.Line, span.Start.Column = 1, 1
	}
	c.diagnostics = append(c.diagnostics, syntax.Diagnostic{
		Filename: filename, Code: code, Message: message, Span: span,
	})
}
